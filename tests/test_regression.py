"""Regression tests for encoder output stability.

These tests compare the current encoder output against previously recorded
fixture arrays (generated by ``tests/generate_fixtures.py``).  If a refactor
changes the numerical output of the encoder, these tests will fail — which is
the point: any behavioural change must be deliberate and the fixtures
regenerated explicitly.

Fixtures are stored as framework-agnostic ``.npz`` files (numpy arrays).

Note: the recorded codebook is *injected* into the encoder under test, so
``regression_data.npz`` protects the message-passing pipeline only. The
seed -> codebook generation of both encoder modes is protected separately by
``seed_fixtures_unit.npz`` (unit-modulus default) and ``seed_fixtures.npz``
(recorded with 0.4.0, reproduced by ``unit_modulus=False``); see
``TestSeedFixtures``.
"""

import json
from pathlib import Path

import numpy as np
import pytest

from hyper_fingerprints.encoder import Encoder

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "regression_data.npz"
ATOL = 1e-10


def _to_numpy(x):
    """Convert encoder output to a plain numpy array."""
    return np.asarray(x)


@pytest.fixture(scope="module")
def fixture_data():
    if not FIXTURE_PATH.exists():
        pytest.skip(
            "Regression fixtures not found. "
            "Run 'python -m tests.generate_fixtures' first."
        )
    raw = np.load(FIXTURE_PATH, allow_pickle=False)
    config = json.loads(bytes(raw["config"]))
    smiles = json.loads(bytes(raw["smiles"]))

    individual_encode = {}
    individual_encode_joint = {}
    for i, smi in enumerate(smiles):
        individual_encode[smi] = raw[f"ind_encode_{i}"]
        individual_encode_joint[smi] = raw[f"ind_joint_{i}"]

    return {
        "config": config,
        "smiles": smiles,
        "codebook": raw["codebook"],
        "individual_encode": individual_encode,
        "individual_encode_joint": individual_encode_joint,
        "batch_encode": raw["batch_encode"],
        "batch_encode_joint": raw["batch_encode_joint"],
    }


@pytest.fixture(scope="module")
def encoder(fixture_data):
    cfg = fixture_data["config"]
    return Encoder(
        dimension=cfg["dimension"],
        depth=cfg["depth"],
        seed=cfg["seed"],
        codebook=fixture_data["codebook"],
    )


# ── Seed -> codebook / output stability ────────────────────────────────


FIXTURE_DIR = Path(__file__).parent / "fixtures"


@pytest.fixture(
    scope="module",
    params=[("seed_fixtures_unit.npz", True), ("seed_fixtures.npz", False)],
    ids=["unit_modulus", "gaussian_0.4.0"],
)
def seed_fixture(request):
    name, unit_modulus = request.param
    path = FIXTURE_DIR / name
    if not path.exists():
        pytest.skip("Seed fixtures not found. Run 'python -m tests.generate_fixtures'.")
    raw = np.load(path, allow_pickle=False)
    cfg = json.loads(str(raw["config"]))
    cfg["unit_modulus"] = unit_modulus
    return raw, cfg


class TestSeedFixtures:
    """Codebooks generated from a seed, and composite-mode outputs, must match
    the values recorded by ``generate_fixtures.py`` (no codebook injection).

    Runs once against the unit-modulus default and once with
    ``unit_modulus=False`` against the file recorded with 0.4.0."""

    def test_legacy_codebook_from_seed(self, seed_fixture):
        raw, cfg = seed_fixture
        enc = Encoder(dimension=cfg["dimension"], seed=cfg["seed"], unit_modulus=cfg["unit_modulus"])
        np.testing.assert_allclose(enc._codebook, raw["legacy_codebook"], atol=ATOL, rtol=0)

    def test_composite_codebooks_from_seed(self, seed_fixture):
        raw, cfg = seed_fixture
        enc = Encoder(
            dimension=cfg["dimension"], depth=cfg["depth"], seed=cfg["seed"], normalize=True,
            features=cfg["features"], graph_features=cfg["graph_features"],
            unit_modulus=cfg["unit_modulus"],
        )
        for name, arr in enc._node_encoder.arrays().items():
            np.testing.assert_allclose(arr, raw[f"node/{name}"], atol=ATOL, rtol=0, err_msg=name)
        for name, arr in enc._graph_encoder.arrays().items():
            np.testing.assert_allclose(arr, raw[f"graph/{name}"], atol=ATOL, rtol=0, err_msg=name)

    def test_composite_outputs(self, seed_fixture):
        raw, cfg = seed_fixture
        enc = Encoder(
            dimension=cfg["dimension"], depth=cfg["depth"], seed=cfg["seed"], normalize=True,
            features=cfg["features"], graph_features=cfg["graph_features"],
            unit_modulus=cfg["unit_modulus"],
        )
        smiles = json.loads(str(raw["composite_smiles"]))
        np.testing.assert_allclose(enc.encode(smiles), raw["composite_encode"], atol=ATOL, rtol=0)
        np.testing.assert_allclose(
            enc.encode_joint(smiles), raw["composite_encode_joint"], atol=ATOL, rtol=0
        )


# ── Individual molecule tests ───────────────────────────────────────────


class TestIndividualEncode:
    """Each molecule encoded alone must match its recorded fixture."""

    def test_encode(self, encoder, fixture_data):
        for smi, expected in fixture_data["individual_encode"].items():
            result = _to_numpy(encoder.encode(smi))
            np.testing.assert_allclose(
                result, expected, atol=ATOL, rtol=0,
                err_msg=f"encode() mismatch for {smi!r}",
            )

    def test_encode_joint(self, encoder, fixture_data):
        for smi, expected in fixture_data["individual_encode_joint"].items():
            result = _to_numpy(encoder.encode_joint(smi))
            np.testing.assert_allclose(
                result, expected, atol=ATOL, rtol=0,
                err_msg=f"encode_joint() mismatch for {smi!r}",
            )


# ── Batch tests ─────────────────────────────────────────────────────────


class TestBatchEncode:
    """Batch encoding of all molecules must match the recorded fixture."""

    def test_encode_batch(self, encoder, fixture_data):
        smiles = fixture_data["smiles"]
        expected = fixture_data["batch_encode"]
        result = _to_numpy(encoder.encode(smiles))
        np.testing.assert_allclose(result, expected, atol=ATOL, rtol=0)

    def test_encode_joint_batch(self, encoder, fixture_data):
        smiles = fixture_data["smiles"]
